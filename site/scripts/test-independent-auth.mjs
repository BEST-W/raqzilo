import assert from "node:assert/strict";
import { randomToken, tokenHash, passwordAllowed, passwordHash, passwordMatches, setupAllowed, cookiePolicy } from "../lib/owner-auth-core.ts";
const password = "owner fixture password 2026";
const [first, second] = await Promise.all([passwordHash(password), passwordHash(password)]);
assert.notEqual(first, second);
assert(await passwordMatches(password, first));
assert(!await passwordMatches("incorrect fixture password", first));
assert(!await passwordMatches(password, "malformed hash"));
assert(!passwordAllowed("short")); assert(!passwordAllowed("x".repeat(129))); assert(passwordAllowed("x".repeat(14)));
const token = randomToken(), expiry = String(Date.now() + 60000);
assert.match(token, /^[a-f0-9]{64}$/); assert.notEqual(token, randomToken());
assert.notEqual(tokenHash(token), token);
assert(setupAllowed(token, token, expiry));
assert(!setupAllowed(token, undefined, expiry));
assert(!setupAllowed(token, token, String(Date.now() - 1)));
assert(!setupAllowed(randomToken(), token, expiry));
assert.match(cookiePolicy("https://example.test"), /HttpOnly; SameSite=Strict; Secure/);
assert(!cookiePolicy("http://localhost").includes("Secure"));
const previous = process.env.VERCEL; process.env.VERCEL = "1";
assert(cookiePolicy("http://localhost").includes("Secure"));
if (previous === undefined) delete process.env.VERCEL; else process.env.VERCEL = previous;
console.log("PASS: salted passwords, password boundaries, expiring activation, opaque sessions, secure cookie policy");
